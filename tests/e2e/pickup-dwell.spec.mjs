import {test,expect} from '@playwright/test'
test('pickup starts only after 100ms of continuous hover',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
 await page.goto('/tests/fixtures/rc2-harness.html')
 const row=page.locator('[data-prts-session-row]').first()
 await expect(row).toBeVisible()
 await page.clock.install()
 await page.clock.pauseAt(new Date())
 await row.hover()
 const bar=row.locator('[data-prts-session-pickup-bar]').first()
 await expect(bar).toHaveCSS('visibility','hidden')
 await expect(bar).toHaveCSS('animation-name','none')
 await page.clock.runFor(80)
 await expect(row).not.toHaveAttribute('data-prts-pickup-ready','')
 await expect(row.locator('[data-prts-session-pickup-baseline]')).toHaveCSS('visibility','visible')
 await page.mouse.move(1200,20)
 await page.clock.runFor(150)
 await expect(row).not.toHaveAttribute('data-prts-pickup-ready','')
 await row.hover()
 await page.clock.runFor(110)
 await expect(bar).toHaveCSS('visibility','visible')
 await expect(bar).toHaveCSS('animation-name','prts-session-pickup-sample')
 await page.mouse.move(1200,20)
 await expect(bar).toHaveCSS('animation-name','none')
})

  expect(matrix.scale).toBeCloseTo(reduced?1:1.025,3)
  if(reduced)expect(matrix.tilt).toBe(0)
  else expect(matrix.tilt).toBeGreaterThan(0)
  if(reduced)expect(await rows.evaluateAll(es=>es.flatMap(e=>e.getAnimations()).length)).toBe(0)
  await page.mouse.up()
  await expect(ghost).toHaveCount(0)
  await expect(page.locator('[data-prts-emblem-status]')).toContainText('已保存')
  await expect(rows.nth(1)).toHaveAttribute('data-emblem-key',first)
  expect(await rows.evaluateAll(es=>es.flatMap(e=>e.getAnimations()).length)).toBe(0)

test('touch long press reorders, edge dragging scrolls and pointer cancellation never saves',async({browser,baseURL})=>{
  const context=await browser.newContext({baseURL,viewport:{width:390,height:844},hasTouch:true,isMobile:true})
  const page=await context.newPage()
  try{
    await start(page);await open(page)
    const rows=page.locator('[data-prts-emblem-list] > li[data-emblem-key]')
    const cdp=await context.newCDPSession(page)
    const scroll=page.locator('[data-prts-theme-settings-scroll]')
    await rows.first().scrollIntoViewIfNeeded()
    const swipe=await rows.first().locator(':scope > span').boundingBox()
    const scrollBefore=await scroll.evaluate(e=>e.scrollTop)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:swipe.x+10,y:swipe.y+8}]})
    for(let step=1;step<=5;step++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:swipe.x+10,y:swipe.y+8-step*18}]})
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await page.waitForTimeout(450)
    expect(await scroll.evaluate(e=>e.scrollTop)).toBeGreaterThan(scrollBefore)
    await expect(page.locator('[data-prts-emblem-drag-ghost]')).toHaveCount(0)
    const first=await rows.first().getAttribute('data-emblem-key')
    const handle=rows.first().locator(':scope > span')
    await handle.scrollIntoViewIfNeeded()
    const box=await handle.boundingBox(), x=box.x+box.width/2,y=box.y+box.height/2
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
    await page.waitForTimeout(470)
    await expect(page.locator('[data-prts-emblem-drag-ghost]')).toBeVisible()
    const viewport=await scroll.boundingBox()
    const before=await scroll.evaluate(e=>e.scrollTop)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:viewport.y+viewport.height-20}]})
    await page.waitForTimeout(900)
    expect(await scroll.evaluate(e=>e.scrollTop)).toBeGreaterThan(before)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    await expect(page.locator('[data-prts-emblem-status]')).toContainText('已保存')
    expect(await rows.first().getAttribute('data-emblem-key')).not.toBe(first)
    const order=await rows.evaluateAll(es=>es.map(e=>e.dataset.emblemKey))
    await rows.first().locator('[data-prts-emblem-reorder]').scrollIntoViewIfNeeded()
    const next=await rows.first().locator('[data-prts-emblem-reorder]').boundingBox()
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:next.x+20,y:next.y+20}]})
    await page.waitForTimeout(470)
    await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]})
    await expect(page.locator('[data-prts-emblem-drag-ghost]')).toHaveCount(0)
    expect(await rows.evaluateAll(es=>es.map(e=>e.dataset.emblemKey))).toEqual(order)
    await page.reload();await open(page)
    expect(await rows.evaluateAll(es=>es.map(e=>e.dataset.emblemKey))).toEqual(order)
  }finally{await context.close()}
})


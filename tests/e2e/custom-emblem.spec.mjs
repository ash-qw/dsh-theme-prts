import { readFile } from 'node:fs/promises'
import { dropFile } from '../helpers/file-drop.mjs'
import { expect, test } from '@playwright/test'

async function start(page, noStorage=false) {
  await page.addInitScript(noStorage=>{
    localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false}))
    if(noStorage)Object.defineProperty(window,'indexedDB',{value:undefined})
  },noStorage)
  await page.goto('/tests/fixtures/rc2-harness.html')
}
async function open(page) {
  if (page.viewportSize().width < 640) await page.locator('[data-prts-rail-launcher]').click()
  await page.locator('[data-prts-rail-brand]').click()
  await page.locator('[data-prts-settings-jump="particles"]').click()
  await expect(page.locator('[data-prts-emblem-add]')).toBeEnabled()
}
async function image(page) {
  const base64=await page.evaluate(()=>{
    const c=document.createElement('canvas');c.width=c.height=192;const ctx=c.getContext('2d')
    ctx.fillStyle='white';ctx.fillRect(0,0,192,192);ctx.fillStyle='black';ctx.fillRect(48,48,96,96)
    return c.toDataURL('image/png').split(',')[1]
  })
  return Buffer.from(base64,'base64')
}
async function upload(page,buffer,name) {
  await dropFile(page,'[data-prts-emblem-workspace]',{name,mimeType:'image/png',buffer})
  await expect(page.locator('[data-prts-emblem-apply]')).toBeEnabled()
}
async function apply(page) {
  await page.locator('[data-prts-emblem-apply]').click()
  await expect(page.locator('[data-prts-emblem-status]')).toContainText('已保存')
  await expect(page.locator('[data-prts-emblem-workspace]')).toBeHidden()
}

async function dragRow(page,from,to) {
  await from.scrollIntoViewIfNeeded();await to.scrollIntoViewIfNeeded()
  const start=await from.locator(':scope > span').boundingBox(), end=await to.boundingBox(), source=await from.boundingBox()
  await page.mouse.move(start.x+start.width/2,start.y+start.height/2)
  await page.mouse.down();await page.waitForTimeout(460)
  await expect(page.locator('[data-prts-emblem-drag-ghost]')).toBeVisible()
  const ghost=await page.locator('[data-prts-emblem-drag-ghost]').boundingBox()
  expect(Math.abs(ghost.x+ghost.width/2-source.x-source.width/2)).toBeLessThan(2)
  expect(ghost.width/source.width).toBeCloseTo(1.025,2)
  expect(Math.abs(ghost.y+ghost.height/2-source.y-source.height/2)).toBeLessThan(2)
  await page.mouse.move(start.x+start.width/2,end.y+end.height/2-12,{steps:6})
  await page.waitForTimeout(80);await page.mouse.up()
  await expect(page.locator('[data-prts-emblem-status]')).toContainText('已保存')
}


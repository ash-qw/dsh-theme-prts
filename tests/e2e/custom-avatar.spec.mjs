import { dropFile } from '../helpers/file-drop.mjs'
import { test,expect } from '@playwright/test'
import sharp from 'sharp'
import { randomBytes } from 'node:crypto'

async function open(page){
  await page.locator('[data-prts-rail-brand]').click()
  await page.locator('[data-prts-settings-jump="appearance"]').click()
  await page.locator('[data-prts-setting-key="conversationStyle"][data-prts-setting-value="deck-chat"]').click()
  await expect(page.locator('[data-prts-avatars]')).toBeVisible()
}
test('avatars upload independently, sync across pages, persist reload and reset to defaults',async({page,context,browser})=>{
  await context.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
  await page.goto('/tests/fixtures/rc2-harness.html')
  await page.addStyleTag({content:'*,*::before,*::after{corner-shape:superellipse(1.5)}'})
  await open(page)
  await page.evaluate(()=>{
    const user=document.createElement('div');user.dataset.chatFlowKind='user'
    user.textContent='Avatar test'
    document.querySelector('[data-chat-flow-kind="assistant-step"]').parentElement.append(user)
  })
  const buffer=await sharp({create:{width:80,height:120,channels:4,background:'#ee5500'}}).png().toBuffer()
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await dropFile(page,'[data-prts-avatar-crop]',{name:'avatar.png',mimeType:'image/png',buffer})
  await page.locator('[data-crop-save]').click()
  await expect(page.locator('[data-prts-avatar-status]')).toContainText('已保存')
  const user=page.locator('[data-prts-avatar-preview="user"]')
  await expect(user).toHaveCSS('background-image',/data:image\/png/)
  expect(await page.locator('[data-chat-flow-kind="user"]').evaluate(e=>getComputedStyle(e,'::after').backgroundImage)).toContain('data:image/png')
  expect(await page.locator('[data-chat-flow-kind="user"]').evaluate(e=>getComputedStyle(e,'::after').content)).toBe('""')
  // Canceling file selection leaves the settings and existing image intact.
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await page.locator('[data-crop-file]').setInputFiles([])
  await expect(page.locator('[data-prts-avatars]')).toBeVisible()
  await page.locator('[data-crop-cancel]').click()
  // Separate connection pools avoid six HTTP/1 SSE streams starving image requests.
  const other=await browser.newPage({baseURL:new URL(page.url()).origin})
  await other.context().addCookies(await context.cookies())
  await other.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
  await other.goto('/tests/fixtures/rc2-harness.html');await open(other)
  await expect(other.locator('[data-prts-avatar-preview="user"]')).toHaveCSS('background-image',/data:image\/png/)
  await page.locator('[data-prts-avatar-preview="assistant"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await page.locator('[data-crop-file]').setInputFiles({name:'avatar.png',mimeType:'image/png',buffer})
  await page.locator('[data-crop-save]').click()
  await expect(page.locator('[data-prts-avatar-status]')).toContainText('已保存')
  await expect(other.locator('[data-prts-avatar-preview="assistant"]')).toHaveCSS('background-image',/data:image\/png/)
  expect(await page.locator('[data-chat-flow-kind="assistant-step"]').evaluate(e=>getComputedStyle(e,'::before').backgroundImage)).toContain('data:image/png')
  await page.locator('[data-prts-avatars]').screenshot({path:'/tmp/prts-avatar-settings.png'})
  await page.locator('[data-prts-setting-key="conversationStyle"][data-prts-setting-value="native"]').click()
  await expect(page.locator('[data-prts-avatars]')).toBeHidden()
  await page.locator('[data-prts-setting-key="conversationStyle"][data-prts-setting-value="deck-chat"]').click()
  await expect(user).toHaveCSS('background-image',/data:image\/png/)
  await page.reload();await open(page)
  await user.click()
  await expect(page.locator('[data-crop-reset]')).toBeEnabled()
  page.once('dialog',d=>d.accept())
  await page.locator('[data-crop-reset]').click()
  await expect(user).toHaveCSS('background-image',/svg.*none/)
  await expect(other.locator('[data-prts-avatar-preview="user"]')).toHaveCSS('background-image',/svg.*none/)
  await expect(page.locator('[data-prts-avatar-preview="assistant"]')).toHaveCSS('background-image',/data:image\/png/)
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await page.locator('[data-crop-file]').setInputFiles({name:'invalid.png',mimeType:'image/png',buffer:Buffer.from('invalid')})
  await expect(page.locator('[data-prts-avatar-crop-status]')).toContainText('无法读取')
  await expect(user).toHaveCSS('background-image',/svg.*none/)
  await other.close()
})

test('avatar settings remain usable on narrow screens',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
  await page.goto('/tests/fixtures/rc2-harness.html')
  await page.locator('[data-prts-rail-launcher]').click()
  await page.addStyleTag({content:'*,*::before,*::after{corner-shape:superellipse(1.5)}'})
  await open(page)
  const section=page.locator('[data-prts-avatars]')
  await section.scrollIntoViewIfNeeded()
  expect(await section.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true)
  const bounds=await section.boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(390)
  for(const width of [390,320]){
    await page.setViewportSize({width,height:844})
    for(const avatar of await section.locator('[data-prts-avatar-preview]').all()){
      const shape=await avatar.evaluate(e=>{const b=e.getBoundingClientRect(),s=getComputedStyle(e);return{width:b.width,height:b.height,radius:s.borderRadius,corner:s.cornerShape,image:s.backgroundImage}})
      expect(shape.width).toBe(44);expect(shape.height).toBe(44);expect(shape.radius).toBe('50%')
      expect(shape.corner).toBe('round');expect(shape.image).toContain('stroke-dasharray')
    }
  }
  await page.setViewportSize({width:390,height:844})
  await section.screenshot({path:'/tmp/prts-avatar-settings-mobile.png'})
  await page.setViewportSize({width:320,height:720})
  await page.locator('[data-prts-avatar-preview="user"]').click()
  const editor=page.locator('[data-prts-avatar-crop]')
  await expect(editor.locator('[data-crop-file]')).toBeEnabled()
  expect(await editor.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true)
  await editor.screenshot({path:'/tmp/prts-avatar-editor-mobile.png'})
})

for(const touch of [false,true])test(`avatar crop supports preview, drag, zoom and cancel (${touch?'touch':'mouse'})`,async({browser,baseURL})=>{
  const context=await browser.newContext({baseURL,viewport:{width:1280,height:900},hasTouch:touch})
  const page=await context.newPage()
  try{
    await context.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
    await page.goto('/tests/fixtures/rc2-harness.html');await open(page)
    const red=await sharp({create:{width:100,height:100,channels:3,background:'#ff0000'}}).png().toBuffer()
    const buffer=await sharp({create:{width:200,height:100,channels:3,background:'#0000ff'}}).composite([{input:red,left:0,top:0}]).png().toBuffer()
    await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await page.locator('[data-crop-file]').setInputFiles({name:'crop.png',mimeType:'image/png',buffer})
    const dialog=page.locator('[data-prts-avatar-crop]'),canvas=dialog.locator('canvas')
    await expect(dialog).toBeVisible()
    await expect(page.locator('[data-crop-reset]')).toBeDisabled()
    await dialog.locator('input[type=range]').fill('2')
    const box=await canvas.boundingBox(),x=box.x+box.width/2,y=box.y+box.height/2
    if(touch){
      const cdp=await context.newCDPSession(page)
      await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
      await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+100,y}]})
      await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    }else{
      await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+100,y,{steps:4});await page.mouse.up()
    }
    const pixel=await canvas.evaluate(c=>[...c.getContext('2d').getImageData(232,160,1,1).data])
    expect(pixel[2]).toBeGreaterThan(240)
    const outside=await canvas.evaluate(c=>c.getContext('2d').getImageData(88,160,1,1).data[0])
    expect(outside).toBeGreaterThan(60);expect(outside).toBeLessThan(110)
    await dialog.screenshot({path:`/tmp/prts-avatar-crop-${touch?'touch':'mouse'}.png`})
    await dialog.locator('[data-crop-cancel]').click()
    await expect(dialog).not.toBeVisible()
    await expect(page.locator('[data-prts-avatars]')).toBeVisible()
    await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(page.locator('[data-crop-file]')).toBeEnabled()
  await page.locator('[data-crop-file]').setInputFiles({name:'crop.png',mimeType:'image/png',buffer})
    await expect(dialog).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(page.locator('[data-prts-avatars]')).toBeVisible()
  }finally{await context.close()}
})

test('saved avatars reopen original image for recropping and support wheel and trackpad zoom',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
  await page.goto('/tests/fixtures/rc2-harness.html');await open(page)
  const red=await sharp({create:{width:100,height:100,channels:3,background:'#ff0000'}}).png().toBuffer()
  const buffer=await sharp({create:{width:200,height:100,channels:3,background:'#0000ff'}}).composite([{input:red,left:0,top:0}]).png().toBuffer()
  const dialog=page.locator('[data-prts-avatar-crop]'),canvas=dialog.locator('canvas')
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(dialog.locator('[data-crop-file]')).toBeEnabled()
  await dialog.locator('[data-crop-file]').setInputFiles({name:'crop.png',mimeType:'image/png',buffer})
  await expect(dialog.locator('[data-crop-save]')).toBeEnabled()
  await canvas.hover();await page.mouse.wheel(0,-200)
  await expect(dialog.locator('input[type=range]')).not.toHaveValue('1')
  await expect(dialog.locator('[data-crop-percent]')).toHaveCount(0)
  await canvas.dispatchEvent('wheel',{deltaY:-30,ctrlKey:true})
  expect(Number(await dialog.locator('input[type=range]').inputValue())).toBeGreaterThan(1.5)
  await dialog.locator('input[type=range]').fill('1')
  await canvas.focus()
  for(let i=0;i<40;i++)await page.keyboard.press('Shift+ArrowRight')
  await dialog.locator('[data-crop-save]').click()
  await expect(dialog).not.toBeVisible()
  await page.reload();await open(page)
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(dialog.locator('[data-crop-save]')).toBeEnabled()
  expect(await canvas.evaluate(c=>c.getContext('2d').getImageData(232,160,1,1).data[2])).toBeGreaterThan(240)
  await canvas.focus()
  for(let i=0;i<50;i++)await page.keyboard.press('Shift+ArrowLeft')
  expect(await canvas.evaluate(c=>c.getContext('2d').getImageData(88,160,1,1).data[0])).toBeGreaterThan(240)
  await dialog.locator('[data-crop-save]').click()
  await expect(dialog).not.toBeVisible()
})


test('replacing an avatar with a near-limit image saves and reopens without stack overflow',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('dsh.ui.prts.v1',JSON.stringify({version:12,enabled:true,bootAnimation:false})))
  await page.goto('/tests/fixtures/rc2-harness.html');await open(page)
  const editor=page.locator('[data-prts-avatar-crop]')
  const small=await sharp({create:{width:64,height:64,channels:3,background:'#f00'}}).png().toBuffer()
  const large=await sharp(randomBytes(1280*1280*3),{raw:{width:1280,height:1280,channels:3}}).png().toBuffer()
  expect(large.length).toBeGreaterThan(4*1024*1024)
  for(const buffer of [small,large]){
    await page.locator('[data-prts-avatar-preview="user"]').click()
    await expect(editor.locator('[data-crop-file]')).toBeEnabled()
    await editor.locator('[data-crop-file]').setInputFiles({name:'avatar.png',mimeType:'image/png',buffer})
    await editor.locator('[data-crop-save]').click()
    await expect(editor).not.toBeVisible()
  }
  await page.locator('[data-prts-avatar-preview="user"]').click()
  await expect(editor.locator('[data-crop-save]')).toBeEnabled()
  await expect(editor.locator('[role=status]')).toContainText('继续调整')
})

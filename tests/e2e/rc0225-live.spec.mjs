import { expect, test } from '@playwright/test'

test.use({ locale: 'zh-CN', storageState: process.env.PRTS_RC022_STATE || undefined })
test.beforeEach(() => {
  test.skip(!process.env.PRTS_RC022_STATE, 'Requires authenticated local 0.2.2-rc.5 storage state')
  test.setTimeout(60_000)
})

for (const scheme of ['dark', 'light']) {
  for (const width of [1440, 390]) {
    test(`0.2.2-rc.5 automatic web search preserves host guidance and provider menus (${scheme}, ${width}) @live-rc0225`, async ({ page }) => {
      const errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.setViewportSize({ width, height: 900 })
      await page.goto(process.env.PRTS_LIVE_URL || 'http://127.0.0.1:3080')
      await expect(page.locator('html')).toHaveAttribute('data-dsh-prts', '', { timeout: 20_000 })
      await page.locator('[data-prts-startup]').waitFor({ state: 'hidden' })
      const version = await page.evaluate(() => window.__DSH_BOOT__.release.version)
      test.skip(['0.2.2-rc.2', '0.2.2-rc.3'].includes(version), 'The updated search guidance is specific to 0.2.2-rc.5')
      expect(version).toBe('0.2.2-rc.5')
      await page.locator('html').evaluate((node, value) => { node.dataset.prtsScheme = value }, scheme)
      const expand = page.getByRole('button', { name: '打开侧边栏', exact: true })
      if (await expand.isVisible()) await expand.click()
      await page.getByRole('button', { name: '插件', exact: true }).click()
      await page.locator('[data-global-panel]').getByText('网页搜索与获取', { exact: true }).click()
      const provider = page.locator('#plugin-config-web-search-provider')
      await expect(provider).toBeVisible()
      test.skip((await provider.innerText()).trim() !== '自动选择', 'Requires automatic search selection; does not modify host settings')
      const section = page.locator('section[aria-labelledby="plugin-config-web-search-section"]')
      const guidance = section.getByText(/^跟随当前会话的模型：/)
      await expect(guidance).toBeVisible()
      await expect(guidance).toContainText('DeepSeek 服务端搜索')
      await expect(guidance).toContainText('DeepSeek Search API')
      const guide = section.getByRole('link', { name: '网页搜索与获取指南', exact: true })
      await expect(guide).toBeVisible()
      await expect(guide).toHaveAttribute('target', '_blank')
      await expect(guide).toHaveAttribute('rel', /noopener/)
      const bounds = await guidance.boundingBox()
      expect(bounds.x).toBeGreaterThanOrEqual(0)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
      expect(await section.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
      await provider.click()
      const menu = page.getByRole('menu').filter({ has: page.getByRole('menuitem', { name: 'DeepSeek 服务端搜索', exact: true }) })
      await expect(menu).toBeVisible()
      await expect(menu.getByRole('menuitem', { name: '自动选择', exact: true })).toBeVisible()
      await expect(menu.getByRole('menuitem', { name: 'DeepSeek Search API', exact: true })).toBeVisible()
      await expect(menu).toHaveAttribute('data-prts-floating-glass', 'menu')
      const menuBounds = await menu.boundingBox()
      expect(menuBounds.x).toBeGreaterThanOrEqual(-1)
      expect(menuBounds.x + menuBounds.width).toBeLessThanOrEqual(width + 1)
      await page.keyboard.press('ArrowDown')
      expect(await menu.evaluate(node => node.contains(document.activeElement))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(menu).toBeHidden()
      await expect(provider).toBeFocused()
      await expect(provider).toHaveText('自动选择')
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
      expect(errors).toEqual([])
    })
  }
}

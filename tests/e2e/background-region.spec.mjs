import {test,expect} from '@playwright/test'
import sharp from 'sharp'

for(const slot of ['full','sidebar','conversation'])test(`modal background protection edits and persists ${slot}`,async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.addInitScript(()=>{if(!localStorage.getItem('prtsFixtureNativeConfig'))localStorage.setItem('prtsFixtureNativeConfig',JSON.stringify({revision:1,value:{enabled:true,bootAnimation:false,motion:'reduced'}}))})
  await page.goto('/tests/fixtures/rc7-harness.html?native-forms')
  const openSettings=async()=>{
    if(await page.locator('[data-prts-rail-launcher]').isVisible())await page.locator('[data-prts-rail-launcher]').click()
    await page.locator('[data-prts-rail-brand]').click();await page.locator('[data-prts-settings-jump="background"]').click()
  }
  await openSettings()
  await page.locator(`[data-prts-setting-key="backgroundMode"][data-prts-setting-value="${slot==='full'?'full':'split'}"]`).click()
  const image=await sharp({create:{width:1200,height:600,channels:3,background:'#326485'}}).composite([{input:Buffer.from('<svg width="1200" height="600"><rect x="960" y="120" width="180" height="180" fill="#f5d65a"/></svg>')}]).png().toBuffer()
  await page.locator(`[data-prts-background-file="${slot}"]`).setInputFiles({name:'subject.png',mimeType:'image/png',buffer:image})
  await expect(page.locator('[data-prts-background-status]')).toContainText('背景已保存')
  const trigger=page.locator(`[data-prts-background-region-open="${slot}"]`)
  const entry=await trigger.boundingBox(),thumbnail=await page.locator(`[data-prts-background-image-controls="${slot}"]`).boundingBox()
  expect(entry.x).toBeGreaterThanOrEqual(thumbnail.x);expect(entry.y+entry.height).toBeLessThanOrEqual(thumbnail.y+thumbnail.height)
  let choosers=0
  const onChooser=chooser=>{choosers++;void chooser.setFiles([])}
  page.on('filechooser',onChooser)
  await page.locator(`[data-prts-background-image-controls="${slot}"]`).click({position:{x:20,y:20}})
  await page.waitForTimeout(100)
  expect(choosers).toBe(0)
  await expect(page.locator(`[data-prts-region-editor="${slot}"]`)).not.toBeVisible()
  await page.locator(`[data-prts-background-upload="${slot}"]`).click()
  await expect.poll(()=>choosers).toBe(1)
  page.off('filechooser',onChooser)
  await page.locator(`[data-prts-background-card="${slot}"]`).screenshot({path:`/tmp/prts-background-toolbar-${slot}.png`})
  await trigger.click()
  const editor=page.locator(`[data-prts-region-editor="${slot}"]`),box=editor.locator('[data-prts-region-box]')
  await expect(editor).toHaveJSProperty('open',true);await expect(box).toBeVisible()
  await expect(editor.locator('input')).toHaveCount(0)
  await expect(editor.locator('[data-prts-region-preview]')).toHaveCount(2)
  if(slot==='sidebar'){
    await expect(editor).toContainText('较窄侧栏 · 264px')
    await expect(editor).toContainText('较宽侧栏 · 420px')
    const small=await editor.locator('[data-prts-region-preview="narrow"]').boundingBox(),large=await editor.locator('[data-prts-region-preview="wide"]').boundingBox()
    expect(Math.abs(small.height-large.height)).toBeLessThan(1)
    expect(large.width).toBeGreaterThan(small.width)
    expect(large.height).toBeGreaterThan(large.width)
  }else await expect(editor).toContainText('横向窗口 · 16:9')
  expect(await box.evaluate(el=>el.style.width)).toBe('50%')
  const geometry=()=>box.evaluate(el=>[el.style.left,el.style.top,el.style.width,el.style.height])
  const original=await geometry()
  await editor.locator('[data-prts-region-stage]').click({position:{x:12,y:12}})
  expect(await geometry()).toEqual(original)
  await box.click()
  expect(await geometry()).toEqual(original)
  await expect(editor.locator('[data-prts-region-handle]')).toHaveCount(8)
  await page.evaluate(()=>document.documentElement.dataset.prtsCursor='prts')
  await box.hover();await expect(box).toHaveCSS('cursor','move')
  for(const [edge,cursor] of Object.entries({n:'ns-resize',s:'ns-resize',e:'ew-resize',w:'ew-resize',nw:'nwse-resize',se:'nwse-resize',ne:'nesw-resize',sw:'nesw-resize'})){
    const handle=editor.locator(`[data-prts-region-handle="${edge}"]`)
    await handle.hover();await expect(handle).toHaveCSS('cursor',cursor)
  }
  for(const edge of ['n','e','s','w']){
    const start=await geometry(),handle=await editor.locator(`[data-prts-region-handle="${edge}"]`).boundingBox()
    await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down()
    await page.mouse.move(handle.x+handle.width/2+8,handle.y+handle.height/2+8,{steps:3});await page.mouse.up()
    const end=await geometry()
    if(edge==='e'||edge==='w'){expect(end[1]).toBe(start[1]);expect(end[3]).toBe(start[3]);expect(end[2]).not.toBe(start[2])}
    else{expect(end[0]).toBe(start[0]);expect(end[2]).toBe(start[2]);expect(end[3]).not.toBe(start[3])}
  }
  await editor.locator('[data-prts-region-create]').click()

  const before=await box.evaluate(el=>el.style.left),rect=await box.boundingBox()
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);await page.mouse.down()
  await page.mouse.move(rect.x+rect.width/2+20,rect.y+rect.height/2+10,{steps:3});await page.mouse.up()
  expect(await box.evaluate(el=>el.style.left)).not.toBe(before)
  await editor.locator('[data-prts-region-handle="se"]').focus();await page.keyboard.press('ArrowRight')
  expect(await box.evaluate(el=>parseFloat(el.style.width))).toBeCloseTo(51)
  await editor.locator('[data-prts-region-save]').click();await expect(editor).not.toBeVisible()
  const snapshot=()=>page.evaluate(async()=>await (await fetch('/prts-theme-api/backgrounds/configuration')).json())
  const saved=(await snapshot())[slot];expect(saved.region.width).toBeCloseTo(.51)
  await page.reload();await openSettings();await trigger.click()
  expect(await box.evaluate(el=>parseFloat(el.style.width))).toBeCloseTo(51)
  await editor.screenshot({path:`/tmp/prts-protection-modal-${slot}.png`})
  await page.setViewportSize({width:480,height:900})
  await expect.poll(()=>page.evaluate(slot=>document.documentElement.style.getPropertyValue(`--prts-protected-${slot}-x`),slot)).not.toBe('')
  expect(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
  await editor.screenshot({path:`/tmp/prts-protection-modal-${slot}-narrow.png`})
  await editor.locator('[data-prts-region-clear]').click();await expect(box).toBeHidden()
  await page.keyboard.press('Escape');await expect(editor).not.toBeVisible();await expect(trigger).toBeFocused()
  expect((await snapshot())[slot].region).toEqual(saved.region)
  await trigger.click();await editor.locator('[data-prts-region-clear]').click();await editor.locator('[data-prts-region-save]').click()
  await expect(editor).not.toBeVisible();const after=(await snapshot())[slot];expect(after.id).toBe(saved.id);expect(after.region).toBeNull()
  expect(errors).toEqual([])
})

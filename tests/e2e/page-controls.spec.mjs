import {test,expect} from '@playwright/test'
import {build} from 'esbuild'
import {readFile} from 'node:fs/promises'
test('page controls preserve form events, keyboard selection and color cancellation',async({page})=>{
 const result=await build({entryPoints:['src/client/page-controls.js'],bundle:true,write:false,format:'iife',globalName:'PageControls'})
 await page.setContent('<html data-dsh-prts><body><dialog open id="panel"><label>模式<select aria-label="模式"><option value="a">选项 A</option><option value="b">选项 B</option></select></label><input type="color" data-prts-setting-color aria-label="流线颜色" value="#123456"><button id="outside">外部</button></dialog></body></html>')
 await page.addStyleTag({content:await readFile('src/styles/prts.css','utf8')})
 await page.addStyleTag({content:await readFile('src/styles/theme-settings-workbench.css','utf8')})
 await page.addScriptTag({content:result.outputFiles[0].text})
 await page.evaluate(()=>{window.controls=PageControls.mountPageControls({panel:document.querySelector('#panel'),window});window.changes=[];document.querySelector('#panel').addEventListener('change',e=>{if(e.target.matches('[data-prts-native-model]'))changes.push(e.target.value)})})
 const combo=page.getByRole('combobox',{name:'模式'})
 await combo.click()
 await expect(page.getByRole('listbox')).toBeVisible()
 await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter')
 await expect(combo).toHaveText('选项 B')
 expect(await page.evaluate(()=>changes)).toEqual(['b'])
 await page.evaluate(()=>document.querySelector('select').value='a')
 await expect(combo).toHaveText('选项 A')
 await combo.click();await page.keyboard.press('Escape')
 await expect(combo).toBeFocused()
 await expect(page.getByRole('listbox')).toHaveCount(0)
 await page.getByRole('button',{name:'流线颜色',exact:true}).click()
 await page.getByRole('textbox',{name:'HEX 颜色'}).fill('#abcdef')
 await page.getByRole('button',{name:'取消',exact:true}).click()
 await expect(page.locator('input[type=color]')).toHaveValue('#123456')
 await page.getByRole('button',{name:'流线颜色',exact:true}).click()
 await page.getByRole('textbox',{name:'HEX 颜色'}).fill('invalid')
 await expect(page.getByRole('button',{name:'应用颜色'})).toBeDisabled()
 await page.getByRole('textbox',{name:'HEX 颜色'}).fill('#abcdef')
 await page.getByRole('button',{name:'应用颜色'}).click()
 expect(await page.evaluate(()=>changes)).toEqual(['b','#abcdef'])
 await expect(page.getByRole('button',{name:'流线颜色',exact:true})).toHaveAttribute('title','#ABCDEF')
 await page.evaluate(()=>controls.dispose())
 await expect(page.locator('.prts-page-control')).toHaveCount(0)
})

 await page.addStyleTag({content:await readFile('src/styles/theme-settings-workbench.css','utf8')})
 await page.addScriptTag({content:result.outputFiles[0].text})
 await page.evaluate(async()=>{
  const canvas=document.createElement('canvas');canvas.width=canvas.height=10
  window.saves=[]
  window.avatar=Avatar.mountAvatarCrop({panel:document.querySelector('#panel'),window,load:async()=>({revision:1,image:canvas.toDataURL().split(',')[1],crop:{zoom:1,x:.5,y:.5}}),onSave:async(...args)=>saves.push(args)})
  await avatar.open('user')
 })
 let nativeDialogs=0;page.on('dialog',async d=>{nativeDialogs++;await d.dismiss()})
 await page.locator('[data-crop-reset]').click()
 await expect(page.getByRole('dialog',{name:'恢复默认头像？'})).toBeVisible()
 expect(await page.getByRole('dialog',{name:'恢复默认头像？'}).evaluate(e=>{const b=e.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth})).toBe(true)
 await page.getByRole('button',{name:'保留头像'}).click()
 expect(await page.evaluate(()=>saves.length)).toBe(0)
 await page.locator('[data-crop-reset]').click()
 await page.locator('[data-confirm]').click()

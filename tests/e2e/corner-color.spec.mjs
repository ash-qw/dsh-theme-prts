import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
test('corner color saves, previews, exports and survives reload',async({page})=>{
 await page.addInitScript(()=>{if(!localStorage.getItem('prtsFixtureNativeConfig'))localStorage.setItem('prtsFixtureNativeConfig',JSON.stringify({revision:1,value:{enabled:true,bootAnimation:false}}))})
 await page.goto('/tests/fixtures/rc7-harness.html?native-forms')
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 const input=page.getByLabel('交互提示框颜色',{exact:true})
 await expect(input).toHaveValue('#f0c800')
 await page.locator('[data-prts-setting-row=cornerColor]').screenshot({path:'/tmp/prts-corner-redesign.png'})
 await page.getByRole('button',{name:'白色',exact:true}).click()
 await expect(input).toHaveValue('#f0c800')
 await expect(page.getByRole('button',{name:'白色',exact:true})).toHaveAttribute('aria-pressed','true')
 await input.evaluate(el=>{el.value='#42b8d5';el.dispatchEvent(new Event('input',{bubbles:true}))})
 await input.dispatchEvent('change')
 await expect.poll(()=>page.evaluate(()=>window.__PRTS_FIXTURE_RUNTIME__.nativeConfigForm.getSnapshot().value.cornerColor)).toBe('#42b8d5')
 await page.getByRole('button',{name:'白色',exact:true}).click()
 await expect(input).toHaveValue('#42b8d5')
 await page.reload()
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 await expect(input).toHaveValue('#42b8d5')

 await page.locator('[data-prts-corner-custom]').click()
 await expect(page.locator('[data-prts-color-editor]')).toBeVisible()
 await page.getByLabel('HEX 颜色').fill('#123abc')
 await page.locator('[data-prts-color-cancel]').click()
 await expect(input).toHaveValue('#42b8d5')
 await page.locator('[data-prts-corner-custom]').click()
 await page.getByLabel('HEX 颜色').fill('oops')
 await page.locator('[data-prts-color-apply]').click()
 await expect(page.locator('[data-prts-color-editor]')).toBeVisible()
 await expect(page.getByLabel('HEX 颜色')).toHaveAttribute('aria-invalid','true')
 await page.getByLabel('R 通道').fill('100')
 await expect(page.getByLabel('HEX 颜色')).toHaveValue('#64B8D5')
 await page.keyboard.press('Escape')
 await expect(page.locator('[data-prts-color-editor]')).toBeHidden()
 await expect(page.locator('[data-prts-theme-settings]')).toBeVisible()
 await page.locator('[data-prts-corner-custom]').click()
 await page.getByLabel('HEX 颜色').fill('#42b8d5')
 await page.screenshot({path:'/tmp/prts-color-editor.png'})
 await page.locator('[data-prts-color-apply]').click()
 await expect(page.locator('[data-prts-color-editor]')).toBeHidden()
 await expect(page.locator('[data-prts-corner-custom]')).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('[data-prts-corner-custom]')).toHaveText('自定义')
 await expect.poll(()=>page.locator('[data-prts-corner-preview]').evaluate(el=>getComputedStyle(el,'::after').content)).toBe(JSON.stringify(''))
 await input.dispatchEvent('change')
 await page.locator('[data-prts-transfer-open]').hover()
 await expect(page.locator('[data-prts-body-target-frame]')).toHaveCSS('color','rgb(66, 184, 213)')
 await page.locator('[data-prts-transfer-open]').click()
 await page.locator('[data-prts-transfer-assets]').uncheck()
 const waiting=page.waitForEvent('download')
 await page.locator('[data-prts-transfer-export]').click()
 const download=await waiting
 expect(JSON.parse(await readFile(await download.path(),'utf8')).preferences.cornerColor).toBe('#42b8d5')
 const imported=JSON.parse(await readFile(await download.path(),'utf8'))
 expect(imported.preferences.cornerColorLinked).toBe(false)
 expect(imported.preferences.cornerColorLight).toBe('#f0c800')
 imported.preferences.cornerColorLight='#65ddb0'
 imported.preferences.cornerCustomColorLight='#123456'
 imported.preferences.cornerColor='#b487ef'
 await page.locator('[data-prts-transfer-file]').setInputFiles({name:'colors.prts-theme.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(imported))})
 await page.locator('[data-prts-transfer-apply]').click()
 await expect(page.locator('[data-prts-transfer-status]')).toContainText('主题已导入并保存')
 await page.reload()
 await expect.poll(()=>page.locator('html').evaluate(n=>getComputedStyle(n).getPropertyValue('--prts-corner-color').trim())).toBe('#b487ef')
 await expect.poll(()=>page.evaluate(()=>window.__PRTS_FIXTURE_RUNTIME__.nativeConfigForm.getSnapshot().value.cornerColorLight)).toBe('#65ddb0')
})


test('day and night palettes remain independent and picker stays beside its button', async ({page}) => {
 await page.addInitScript(()=>{if(!localStorage.getItem('prtsFixtureNativeConfig'))localStorage.setItem('prtsFixtureNativeConfig',JSON.stringify({revision:1,value:{enabled:true,bootAnimation:false,preferencesInitialized:true,cornerColor:'#42b8d5',cornerCustomColor:'#123456'}}))})
 await page.goto('/tests/fixtures/rc7-harness.html?native-forms')
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 const row=page.locator('[data-prts-setting-row=cornerColor]')
 const input=row.locator('input[type=color]')
 const custom=row.locator('[data-prts-corner-custom]')
 const inputBox=await input.boundingBox(), buttonBox=await custom.boundingBox()
 expect(Math.abs(inputBox.x-buttonBox.x)).toBeLessThan(10)
 expect(Math.abs(inputBox.y-buttonBox.y)).toBeLessThan(2)
 expect(inputBox.width).toBeGreaterThan(20)
 await row.locator('[data-prts-corner-mode=light]').click()
 await expect(page.locator('html')).toHaveAttribute('data-prts-scheme','dark')
 await expect(input).toHaveValue('#123456')
 await input.evaluate(el=>{el.value='#abcdef';el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}))})
 const activeColor=()=>page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--prts-corner-color').trim())
 await expect.poll(activeColor).toBe('#42b8d5')
 await row.getByRole('button',{name:'白色',exact:true}).click()
 await expect(input).toHaveValue('#abcdef')
 await row.locator('[data-prts-corner-sync]').click()
 await expect.poll(activeColor).toBe('#ffffff')
 await expect(row.locator('[data-prts-corner-modes]')).toBeHidden()
 await expect(row.getByRole('switch',{name:'日夜共用'})).toBeChecked()
 await expect(input).toHaveValue('#abcdef')
 await expect(custom).toHaveAttribute('aria-pressed','false')
 await row.getByRole('button',{name:'蓝色',exact:true}).click()
 await expect.poll(activeColor).toBe('#6eb7f3')
 await row.locator('[data-prts-corner-custom]').click()
 await page.getByLabel('HEX 颜色').fill('#abcdef')
 await expect.poll(activeColor).toBe('#abcdef')
 await page.locator('[data-prts-color-cancel]').click()
 await expect.poll(activeColor).toBe('#6eb7f3')
 await page.screenshot({path:'/tmp/prts-linked-colors.png'})
 await page.reload()
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 await expect(row.getByRole('switch',{name:'日夜共用'})).toBeChecked()
 await expect(row.locator('[data-prts-corner-modes]')).toBeHidden()
 await row.getByRole('button',{name:'白色',exact:true}).click()
 await row.locator('[data-prts-corner-sync]').click()
 await expect(row.locator('[data-prts-corner-modes]')).toBeVisible()
 await expect.poll(activeColor).toBe('#42b8d5')
 await expect(row.locator('[data-prts-corner-mode=light]')).toHaveAttribute('aria-pressed','true')
 await row.locator('[data-prts-corner-sync]').click()
 await row.locator('[data-prts-corner-custom]').click()
 await page.getByLabel('HEX 颜色').fill('#765432')
 await page.locator('[data-prts-color-apply]').click()
 await row.getByRole('button',{name:'蓝色',exact:true}).click()
 await page.reload()
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 await expect.poll(activeColor).toBe('#6eb7f3')
 await expect(input).toHaveValue('#765432')
 await row.locator('[data-prts-corner-sync]').click()
 await expect.poll(activeColor).toBe('#42b8d5')
 await row.locator('[data-prts-corner-mode=dark]').click()
 await expect(input).toHaveValue('#123456')
 await row.getByRole('button',{name:'紫色',exact:true}).click()
 await expect.poll(activeColor).toBe('#b487ef')
 await row.locator('[data-prts-corner-mode=light]').click()
 await expect(row.getByRole('button',{name:'蓝色',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(input).toHaveValue('#765432')
 await page.screenshot({path:'/tmp/prts-day-night-palette.png'})
 await page.reload()
 await page.locator('[data-prts-rail-brand]').click()
 await page.locator('#prts-tab-interaction').click()
 await expect(input).toHaveValue('#123456')
 await row.locator('[data-prts-corner-mode=light]').click()
 await expect(input).toHaveValue('#765432')
 await page.locator('html').evaluate(el=>el.setAttribute('data-prts-scheme','light'))
 await expect.poll(activeColor).toBe('#6eb7f3')
})

import test from 'node:test'
import assert from 'node:assert/strict'
import { JSDOM } from 'jsdom'
import { opacityDialMarkup, mountOpacityDials } from '../src/client/opacity-dial.js'
import { DEFAULT_PREFERENCES, normalizePreferences } from '../src/client/preferences.js'

test('opacity defaults and normalization preserve existing material strengths', () => {
  const defaults = normalizePreferences({})
  assert.equal(defaults.sidebarOpacity,.06);assert.equal(defaults.railOpacity,.3);assert.equal(defaults.bakerOpacity,.5);assert.equal(defaults.classicUserOpacity,.5)
  const normalized = normalizePreferences({sidebarOpacity:-1,railOpacity:2,bakerOpacity:NaN,classicUserOpacity:2})
  assert.equal(normalized.sidebarOpacity,0);assert.equal(normalized.railOpacity,1);assert.equal(normalized.bakerOpacity,.5);assert.equal(normalized.classicUserOpacity,1)
  assert.deepEqual([defaults.sidebarBlur, defaults.railBlur, defaults.bakerBlur, defaults.classicUserBlur], [8,12,8,8])
  const blur = normalizePreferences({sidebarBlur:-1,railBlur:44,bakerBlur:7.6,classicUserBlur:NaN})
  assert.deepEqual([blur.sidebarBlur,blur.railBlur,blur.bakerBlur,blur.classicUserBlur], [0,32,8,8])
})
test('dial supports exact entry, keyboard, preview without writes and cancel rollback', () => {
  const dom = new JSDOM(opacityDialMarkup()), w = dom.window, section = w.document.body, changes = []
  const dials = mountOpacityDials({section,window:w,onChange:(...args)=>changes.push(args)})
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'full'}, {full:{id:'test'}})
  const svg = section.querySelector('[data-prts-opacity-dial] svg'), input = section.querySelector('input')
  const reset = section.querySelector('[data-prts-opacity-control="sidebarOpacity"] [data-prts-opacity-reset]')
  assert.equal(reset.querySelector('svg')?.getAttribute('aria-hidden'),'true')
  assert.equal(reset.getAttribute('data-prts-opacity-reset-tooltip'),'恢复到 94%')
  svg.dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true}))
  assert.deepEqual(changes.pop(),['sidebarOpacity',.05])
  input.value='32';input.dispatchEvent(new w.Event('change'))
  assert.deepEqual(changes.pop(),['sidebarOpacity',.68])
  svg.getBoundingClientRect = ()=>({left:0,top:0,width:200,height:200})
  const pointer = (type, props) => { const e=new w.Event(type);Object.assign(e,{pointerId:1,button:0,...props});svg.dispatchEvent(e) }
  pointer('pointerdown',{clientX:180,clientY:100})
  assert.equal(changes.length,0)
  assert.notEqual(input.value,'32')
  pointer('pointercancel',{})
  assert.equal(input.value,'32');assert.equal(changes.length,0)
  assert.equal(w.document.documentElement.style.getPropertyValue('--prts-sidebar-opacity'),'68%')
  pointer('pointerdown',{clientX:180,clientY:100});pointer('pointerup',{})
  assert.equal(changes.length,1)
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'off'}, {})
  assert.equal(section.querySelector('fieldset').hidden,true)
  dials.dispose();dom.window.close()
})

test('classic user-message opacity is active only with a conversation wallpaper', () => {
  const dom = new JSDOM(opacityDialMarkup()), w = dom.window, section = w.document.body, changes = []
  const dials = mountOpacityDials({section,window:w,onChange:(...args)=>changes.push(args)})
  const classic = section.querySelector('[data-prts-opacity-control="classicUserOpacity"]')
  const baker = section.querySelector('[data-prts-opacity-control="bakerOpacity"]')
  const rail = section.querySelector('[data-prts-opacity-control="railOpacity"]')
  const note = section.querySelector('[data-prts-opacity-control="classicUserOpacity"] [data-prts-opacity-note]')
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'split',conversationStyle:'native'}, {sidebar:{id:'sidebar'}})
  assert.equal(classic.hidden,false)
  assert.equal(baker.hidden,true)
  assert.equal(rail.hidden,false)
  assert.equal(rail.querySelector('[data-prts-opacity-note]').textContent,'')
  assert.equal(note.textContent,'当前未启用此材质')
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'split',conversationStyle:'native'}, {conversation:{id:'conversation'}})
  assert.equal(note.textContent,'')
  const input = section.querySelector('[data-prts-opacity-control="classicUserOpacity"] input')
  input.value='76';input.dispatchEvent(new w.Event('change'))
  assert.deepEqual(changes.pop(),['classicUserOpacity',.24])
  assert.equal(w.document.documentElement.style.getPropertyValue('--prts-classic-user-opacity'),'24%')
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'full',conversationStyle:'deck-chat'}, {full:{id:'full'}})
  assert.equal(classic.hidden,true)
  assert.equal(baker.hidden,false)
  assert.equal(rail.hidden,false)
  assert.equal(note.textContent,'当前未启用此材质')
  dials.dispose();dom.window.close()
})

test('blur previews immediately, saves on change, resets and hides without an image', () => {
  const dom = new JSDOM(opacityDialMarkup()), w = dom.window, section = w.document.body, changes = []
  w.document.documentElement.setAttribute('data-dsh-prts', '')
  const dials = mountOpacityDials({section,window:w,onChange:(...args)=>changes.push(args)})
  const control = section.querySelector('[data-prts-opacity-control="sidebarOpacity"] [data-prts-blur-control]')
  const range = control.querySelector('input'), output = control.querySelector('output')
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'full'}, {})
  assert.equal(control.hidden,true)
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'full'}, {full:{id:'image'}})
  assert.equal(control.hidden,false)
  range.value='19';range.dispatchEvent(new w.Event('input',{bubbles:true}))
  assert.equal(output.value,'19px')
  assert.equal(w.document.documentElement.style.getPropertyValue('--prts-sidebar-blur'),'19px')
  assert.deepEqual(changes,[])
  range.dispatchEvent(new w.Event('change',{bubbles:true}))
  assert.deepEqual(changes.pop(),['sidebarBlur',19])
  control.querySelector('[data-prts-blur-reset]').click()
  assert.deepEqual(changes.pop(),['sidebarBlur',8])
  dials.update({...DEFAULT_PREFERENCES,backgroundMode:'split'}, {conversation:{id:'conversation'}})
  assert.equal(control.hidden,true)
  dials.dispose();dom.window.close()
})

export const API = '/prts-theme-api/emblems'
export const DEFAULT_PARAMS = Object.freeze({mode:'auto',lineSource:'edges',cleanup:2,threshold:128,zoom:.85,x:0,y:0})
export function fault(status,message) { return Object.assign(new Error(message),{status}) }
export function parameters(input = {}, base = DEFAULT_PARAMS) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) throw fault(400,'编辑参数无效')
  const result = {...DEFAULT_PARAMS,...base,...input}
  if (Object.keys(result).some(k=>!Object.hasOwn(DEFAULT_PARAMS,k)) || !['auto','alpha','dark','light','lineart'].includes(result.mode)
    || !['edges','ink'].includes(result.lineSource) || !Number.isInteger(result.cleanup) || result.cleanup<0 || result.cleanup>12
    || !Number.isInteger(result.threshold) || result.threshold<1 || result.threshold>254
    || !Number.isFinite(result.zoom) || result.zoom<.5 || result.zoom>2
    || !Number.isFinite(result.x) || Math.abs(result.x)>.5 || !Number.isFinite(result.y) || Math.abs(result.y)>.5) throw fault(400,'编辑参数超出范围')
  return result
}
export function processImage(bytes, params, signal, prepared, reusableWorker) {
  signal?.throwIfAborted()
  return new Promise((resolve,reject)=>{
    const worker = reusableWorker || new Worker(new URL('./image-worker.js',import.meta.url), {workerData:{bytes,params,prepared},execArgv:[]})
    worker.ref()
    let settled = false
    const finish = async (error,value) => {
      if(settled)return; settled=true;clearTimeout(timer);signal?.removeEventListener('abort',abort)
      if(error || !reusableWorker) await worker.terminate()
      worker.off('error',onError);worker.off('exit',onExit);worker.off('message',onMessage)
      worker.unref()
      if(error)reject(error);else resolve(value)
    }
    const abort = ()=>void finish(signal.reason || new Error('已取消'))
    const onError = error=>void finish(error)
    const onExit = code=>{if(!settled)void finish(new Error(`图片处理进程提前退出 (${code})`))}
    const onMessage = result=>void finish(result.error?fault(400,result.error):null,result)
    const timer = setTimeout(()=>void finish(fault(408,'图片处理超时，请缩小图片后重试')),15000)
    signal?.addEventListener('abort',abort,{once:true})
    worker.once('error',onError);worker.once('exit',onExit);worker.once('message',onMessage)
    if(signal?.aborted)abort()
    else if(reusableWorker) worker.postMessage({bytes,params,prepared})
  })
}

async function atomic(path,value) {
  const temp = `${path}.${randomUUID()}.tmp`
  await writeFile(temp,value,{mode:0o600});await rename(temp,path)
}
const idPattern = /^[a-zA-Z0-9-]{1,80}$/
export function checkedId(id) { if(typeof id!=='string'||!idPattern.test(id))throw fault(400,'徽记标识无效');return id }

export async function createEmblemService(directory) {
  await mkdir(directory,{recursive:true,mode:0o700})
  let state = {revision:0,configuration:defaultEmblemConfiguration(EMBLEMS)}
  try {
    const stored=JSON.parse(await readFile(join(directory,'configuration.json'),'utf8'))
    if(!Number.isInteger(stored.revision)||!validEmblemConfiguration(stored.configuration,EMBLEMS))throw Error('已保存的徽记配置无效')
    state=stored
  } catch(error) { if(error.code!=='ENOENT')throw error }
  let queue=Promise.resolve(), previewQueue=Promise.resolve(), preparedCache, imageWorker, workerIdleTimer, disposed=false
  const listeners=new Set()
  const serialize=fn=>{const next=queue.then(fn);queue=next.catch(()=>{});return next}
  const snapshot=()=>structuredClone(state)
  const draft=async id=>{
    try{return JSON.parse(await readFile(join(directory,`${checkedId(id)}.draft.json`),'utf8'))}
    catch(error){if(error.code==='ENOENT')throw fault(404,'草稿不存在');throw error}
  }
  const save = (configuration,revision,signal)=>serialize(async()=>{
    signal?.throwIfAborted()
    if(revision!==state.revision)throw fault(409,'徽记设置已在其他会话或页面更新，请重新读取后再操作')
    if(configuration?.version!==2 || !Array.isArray(configuration.conversation) || configuration.conversation.length<1 || configuration.conversation.length>12)throw fault(400,'徽记配置无效')
    // Custom entries must be generated by this service; clients cannot inject arbitrary particle arrays.
    const canonical=structuredClone({version:2,hero:configuration.hero,conversation:configuration.conversation})
    const resolveEntry=async entry=>{
      if(!entry || typeof entry!=='object')throw fault(400,'徽记配置无效')
      if(entry.kind==='builtin')return {kind:'builtin',...EMBLEMS.find(e=>e.key===entry.key)}
      if(entry.kind!=='custom')throw fault(400,'徽记类型无效')
      const source=await draft(entry.draftId)
      return {...source.value,kind:'custom',key:entry.key,label:entry.label,draftId:source.id}
    }
    if(canonical.hero)canonical.hero=await resolveEntry(canonical.hero)
    canonical.conversation=await Promise.all(canonical.conversation.map(resolveEntry))
    if(!validEmblemConfiguration(canonical,EMBLEMS))throw fault(400,'徽记配置无效')
    const next={revision:state.revision+1,configuration:canonical}
    signal?.throwIfAborted();await atomic(join(directory,'configuration.json'),JSON.stringify(next));state=next
    for(const fn of listeners) {try{fn(state.revision)}catch{}}
    return snapshot()
  })
  return {
    snapshot,save,draft,
    async dispose() {
      disposed=true;clearTimeout(workerIdleTimer);preparedCache=undefined
      const worker=imageWorker;imageWorker=undefined
      if(worker)await worker.terminate()
    },
    async exportAsset(id) {
      const d=await draft(id)
      const bytes=await readFile(join(directory,`${d.sourceId}.source`))
      return {format:'prts-emblem',version:1,label:d.label,params:d.params,image:bytes.toString('base64')}
    },
    async importAsset(asset,signal) {
      if(asset?.format!=='prts-emblem'||asset.version!==1)throw fault(400,'不支持的徽记素材包格式或版本')
      if(typeof asset.label!=='string'||!asset.label.trim()||asset.label.length>100)throw fault(400,'徽记名称无效')
      if(typeof asset.image!=='string'||!asset.image.length||asset.image.length>Math.ceil(8*1024*1024/3)*4
        || !/^[A-Za-z0-9+/]+={0,2}$/.test(asset.image)||asset.image.length%4!==0)throw fault(400,'素材包图片编码或大小无效')
      const bytes=Buffer.from(asset.image,'base64')
      if(bytes.toString('base64')!==asset.image)throw fault(400,'素材包图片编码无效')
      // Rebuild from the editable source; never trust particle arrays or filesystem paths in a package.
      return this.preview({bytes,params:parameters(asset.params),label:asset.label},signal)
    },
    previewPath: id=>join(directory,`${checkedId(id)}.png`),
    subscribe(fn){listeners.add(fn);return()=>listeners.delete(fn)},
    preview({bytes,params={},baseId,label},signal) {
      const pending = previewQueue.then(async () => {
        if(disposed)throw fault(503,'徽记服务已关闭')
        signal?.throwIfAborted()
        const previous=baseId?await draft(baseId):null
        const effective=parameters(params,previous?.params)
        if(previous)bytes=await readFile(join(directory,`${previous.sourceId}.source`))
        if(!bytes?.length || bytes.length>8*1024*1024)throw fault(400,'图片须为 8 MB 以内的 PNG、JPEG 或 WebP')
        const drafts=(await readdir(directory)).filter(f=>f.endsWith('.draft.json'))
        if(drafts.length>=200)await serialize(async()=>{
          const protectedIds=new Set([previous?.id,state.configuration.hero?.draftId,...state.configuration.conversation.map(e=>e.draftId)])
          const records=await Promise.all(drafts.map(file=>draft(file.slice(0,-11))))
          const expired=records.filter(d=>!protectedIds.has(d.id)).sort((a,b)=>a.createdAt-b.createdAt).slice(0,drafts.length-199)
          const expiredIds=new Set(expired.map(d=>d.id))
          const retainedSources=new Set(records.filter(d=>!expiredIds.has(d.id)).map(d=>d.sourceId))
          for(const d of expired){await unlink(join(directory,`${d.id}.draft.json`));await unlink(join(directory,`${d.id}.png`))}
          for(const sourceId of new Set(expired.map(d=>d.sourceId)))if(!retainedSources.has(sourceId))await unlink(join(directory,`${sourceId}.source`))
        })
        signal?.throwIfAborted()
        const sourceHash=createHash('sha256').update(bytes).digest('hex')
        const cacheKey=`${sourceHash}:${effective.zoom}`
        clearTimeout(workerIdleTimer)
        if (!imageWorker || imageWorker.threadId === -1) imageWorker = new Worker(new URL('./image-worker.js',import.meta.url),{execArgv:[]})
        let result
        try {
          result=await processImage(bytes,effective,signal,preparedCache?.key===cacheKey?preparedCache.data:undefined,imageWorker)
        } finally {
          // Reuse the warmed-up worker while editing, then release its memory.
          if (!disposed) {
          workerIdleTimer=setTimeout(()=>{
            void imageWorker?.terminate();imageWorker=undefined;preparedCache=undefined
          },30000)
          workerIdleTimer.unref()
          }
        }
        if(disposed)throw fault(503,'徽记服务已关闭')
        preparedCache={key:cacheKey,data:result.prepared}
        signal?.throwIfAborted()
        const id=randomUUID(),sourceId=sourceHash
        const value={id,sourceId,params:effective,label:String(label||previous?.label||'自定义徽记').slice(0,100),createdAt:Date.now(),value:result.value,previewPoints:result.previewPoints}
        await atomic(join(directory,`${sourceId}.source`),bytes)
        await atomic(join(directory,`${id}.png`),result.preview)
        await atomic(join(directory,`${id}.draft.json`),JSON.stringify(value))
        return value
      })
      // A cancelled worker must fully exit before the next request starts.
      previewQueue=pending.catch(()=>{})
      return pending
    },
    async image(id,source=false) {const d=await draft(id);return readFile(join(directory,source?`${d.sourceId}.source`:`${d.id}.png`))},
    async apply({draftId,target,entryKey,revision},signal) {
      const d=await draft(draftId),configuration=snapshot().configuration
      const entry={...d.value,kind:'custom',key:randomUUID(),label:d.label,draftId:d.id}
      if(target==='hero')configuration.hero=entry
      else if(target==='add')configuration.conversation.push(entry)
      else if(target==='replace') {
        const index=configuration.conversation.findIndex(e=>e.key===entryKey)
        if(index<0)throw fault(404,'要替换的正文徽记不存在')
        configuration.conversation[index]=entry
      } else throw fault(400,'应用位置无效')
      return save(configuration,revision,signal)
    },
  }
}
export function draftView(d) {
  return {draftId:d.id,label:d.label,params:d.params,particles:Object.fromEntries(Object.entries(d.value.targets).map(([k,v])=>[k,v.length])),previewUrl:`${API}/draft/${d.id}/preview.png`}
}
export function stateView(state) {
  const entry=e=>e?{key:e.key,label:e.label,kind:e.kind,...(e.draftId?{draftId:e.draftId}:{})}:null
  return {revision:state.revision,scope:'当前 DSH 实例，跨工作区和会话共享',hero:entry(state.configuration.hero),conversation:state.configuration.conversation.map(entry)}
}
